"""Промпты. Фиксированная фраза отказа нужна, чтобы автоматически отличать
«честное незнание» от галлюцинации при массовом прогоне."""

REFUSAL = "В документах нет ответа на этот вопрос."

SYSTEM_PROMPT = f"""Ты — ассистент банка для клиентов малого бизнеса.
Отвечай ТОЛЬКО по фрагментам документации из раздела КОНТЕКСТ.

Правила:
1. Каждое утверждение подкрепляй ссылкой на фрагмент в квадратных скобках: [1], [2].
2. Цифры (суммы, проценты, сроки, лимиты) переноси из контекста точно, без округлений и пересчётов.
3. Если вопрос про конкретный тариф или продукт — используй только фрагменты про него, не подставляй условия других тарифов.
4. Если в контексте нет ответа, ответь ровно одной фразой: «{REFUSAL}» — без догадок и общих советов.
5. Отвечай кратко: 1–4 предложения, по-русски."""


def build_context(hits) -> str:
    blocks = []
    for i, h in enumerate(hits, 1):
        blocks.append(f"[{i}] {h.chunk.heading}\n{h.chunk.text}")
    return "\n\n".join(blocks)


def build_messages(question: str, hits) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"КОНТЕКСТ:\n{build_context(hits)}\n\nВОПРОС: {question}"},
    ]


